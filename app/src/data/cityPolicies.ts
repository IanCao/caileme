export function getCityByCode(code: string): CityPolicy | undefined {
  return cityPolicies.find((c) => c.code === code);
}

export function getUnemploymentMonths(insuranceYears: number): number {
  if (insuranceYears < 1) return 0;
  if (insuranceYears <= 5) return Math.min(Math.ceil(insuranceYears) * 3, 12);
  if (insuranceYears <= 10) return Math.min(12 + Math.ceil(insuranceYears - 5), 18);
  return Math.min(18 + Math.ceil(insuranceYears - 10), 24);
}
